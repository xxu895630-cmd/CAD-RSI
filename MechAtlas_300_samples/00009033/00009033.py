import cadquery as cq

profile_plane = cq.Plane(origin=(0.0, 0.0, 10.0), xDir=(1.0, 0.0, 0.0), normal=(0.0, 0.0, 1.0))

outer_profile = (cq.Workplane(profile_plane).moveTo(-14.652468541175041, -17.394376795869096)
    .lineTo(15.347531458824944, -17.39437679586909)
    .lineTo(18.347531458824953, -14.394376795869096)
    .lineTo(18.347531458824953, 15.605623204130888)
    .lineTo(15.347531458824951, 18.605623204130904)
    .lineTo(-14.652468541175033, 18.605623204130904)
    .lineTo(-17.65246854117505, 15.605623204130902)
    .lineTo(-17.652468541175043, -14.394376795869075)
    .lineTo(-14.652468541175041, -17.394376795869096)
    .close().val())

opening_1 = (cq.Workplane(profile_plane).moveTo(-15.630390602532996, 13.333545265488773)
    .threePointArc((-12.380390602532998, 16.583545265488773), (-9.130390602532998, 13.333545265488773))
    .threePointArc((-12.380390602532998, 10.083545265488773), (-15.630390602532998, 13.333545265488773))
    .close().val())

opening_2 = (cq.Workplane(profile_plane).moveTo(9.825453520182899, -12.122298857226951)
    .threePointArc((13.075453520182895, -8.872298857226953), (16.325453520182894, -12.122298857226951))
    .threePointArc((13.075453520182895, -15.37229885722695), (9.825453520182897, -12.122298857226951))
    .close().val())

opening_3 = (cq.Workplane(profile_plane).moveTo(-9.65246854117504, 0.6056232041309014)
    .threePointArc((0.3475314588249607, 10.6056232041309), (10.34753145882496, 0.6056232041309002))
    .threePointArc((0.3475314588249583, -9.3943767958691), (-9.65246854117504, 0.6056232041309014))
    .close().val())

extrusion_vector = (0.0, 0.0, -10.0)

solid = cq.Solid.extrudeLinear(outer_profile, [opening_1, opening_2, opening_3], cq.Vector(*extrusion_vector))

result = cq.Workplane().newObject([solid])
